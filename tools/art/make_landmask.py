#!/usr/bin/env python3 -I
"""Land mask for the FLY-screen globe (src/globe.js): rasterise Natural Earth 50m land (public domain,
naturalearthdata.com) into a 0.5 degree land/sea grid, written as src/landmask.js (generated: never edit it).

  python3 -I tools/art/make_landmask.py ~/ne-data50/ne_50m_land.geojson

The geojson is DOWNLOADED DATA: keep it in its own empty directory, pass it by path, run with -I.
Output: LAND_RLE rows (north first) of alternating run lengths sea, land, sea... in base 36, joined by '|';
ISLANDS = centres of land too small to fill a cell centre (Honolulu's Oahu...), kept if at least 0.3 degrees across or
within 1.5 degrees of a game city, which the globe stamps as single pixels so a city on a small island is never in the sea.  Deterministic: the same input, the same file."""
import json, math, os, re, sys

W, H = 720, 360                      # 0.5 degree cells
CELL = 360.0 / W
src = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
# The game's own cities (src/cities.js: declared data, read as text): a speck of island is kept only if it is big enough to see or has a city on it.
cities = [(float(a), float(b)) for a, b in re.findall(r"lat: (-?[\d.]+), lon: (-?[\d.]+)", open(os.path.join(HERE, '..', '..', 'src', 'cities.js')).read())]
assert len(cities) >= 100, f'read {len(cities)} cities from src/cities.js'
d = json.load(open(src))
polys = []
for f in d['features']:
    g = f['geometry']
    polys += g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]

grid = [bytearray(W) for _ in range(H)]
islands = []
for rings in polys:
    xs_all = [p[0] for r in rings for p in r]; ys_all = [p[1] for r in rings for p in r]
    j0 = max(0, int((90 - max(ys_all)) / CELL - 0.5)); j1 = min(H - 1, int((90 - min(ys_all)) / CELL + 0.5))
    hit = 0
    for j in range(j0, j1 + 1):
        lat = 90 - (j + 0.5) * CELL
        xs = []
        for r in rings:
            for (x1, y1), (x2, y2) in zip(r, r[1:]):
                if (y1 <= lat < y2) or (y2 <= lat < y1):
                    xs.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            i0 = max(0, math.ceil((a + 180) / CELL - 0.5)); i1 = min(W - 1, math.ceil((b + 180) / CELL - 0.5) - 1)
            for i in range(i0, i1 + 1): grid[j][i] = 1
            hit += max(0, i1 - i0 + 1)
    if hit < 2:   # too small for even two cell centres: a dot, but only where it can be seen or a city stands
        la, lo = (min(ys_all) + max(ys_all)) / 2, (min(xs_all) + max(xs_all)) / 2
        big = max(max(ys_all) - min(ys_all), max(xs_all) - min(xs_all)) >= 0.3
        if big or any(abs(la - a) < 1.5 and abs(lo - b) < 1.5 for a, b in cities): islands.append((round(la, 2), round(lo, 2)))

def b36(n):
    s = ''
    while True:
        n, r = divmod(n, 36); s = '0123456789abcdefghijklmnopqrstuvwxyz'[r] + s
        if not n: return s
rows = []
for row in grid:
    runs, cur, n = [], 0, 0
    for v in row:
        if v == cur: n += 1
        else: runs.append(n); cur = v; n = 1
    runs.append(n)
    rows.append(','.join(b36(x) for x in runs))
rle = '|'.join(rows)
islands = sorted(set(islands))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'landmask.js')
with open(out, 'w') as f:
    f.write("// GENERATED by tools/art/make_landmask.py from Natural Earth 50m land (public domain). Do not edit by hand.\n"
            "// 0.5 degree cells, row 0 = north (lat 90..-90), column 0 = lon -180. LAND_RLE: per row, alternating run lengths\n"
            "// (sea, land, sea...) in base 36, rows joined by '|'. ISLANDS: [lat, lon] of land too small for a cell centre.\n"
            f"export const LAND_W = {W}, LAND_H = {H};\n"
            f"export const LAND_RLE = '{rle}';\n"
            f"export const ISLANDS = {json.dumps([list(i) for i in islands], separators=(',', ':'))};\n")
land = sum(sum(r) for r in grid)
print(f'{len(polys)} polygons -> {land} land cells of {W * H} ({100 * land / (W * H):.1f}%), {len(islands)} islands, {os.path.getsize(out) / 1024:.1f} KB')
