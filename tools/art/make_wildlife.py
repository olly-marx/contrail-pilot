"""Draw every species in species.py that has dials, and write src/wildlife.js for the game.

Run from the repo root:  python3 tools/art/make_wildlife.py [preview.png]
Hand-drawn species (art='hand') keep their make_sprites.py PNGs; species with art=None are
listed in wildlife.js with sprite: null so the game can show a "coming soon" silhouette.
"""
import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from creatures import frames_same_size   # noqa: E402
from shapes import render   # noqa: E402

SMALL, PORTRAIT = 1.5, 4      # px per unit: in-flight sprite, collection-screen portrait
from species import REGIONS, SPECIES, TERRAIN_ONLY, TREES   # noqa: E402
from trees import WOODLAND, TREE_SMALL, TREE_PORTRAIT, render_tree   # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
A = ROOT / 'assets'


def key(sp):
    return ('sky-' if sp['kind'] == 'bird' else 'animal-') + sp['id']


def main(preview=None):
    drawn = []
    for sp in SPECIES:
        if isinstance(sp['art'], dict):
            frames = frames_same_size(render(sp['art'], 0, SMALL), render(sp['art'], 1, SMALL))
            for i, im in enumerate(frames):
                im.save(A / f'{key(sp)}-{i}.png')
            big = frames_same_size(render(sp['art'], 0, PORTRAIT), render(sp['art'], 1, PORTRAIT))
            for i, im in enumerate(big):
                im.save(A / 'ui' / f'portrait-{key(sp)}-{i}.png')
            drawn.append((sp, frames))
            print('drew', key(sp), frames[0].size)
    for t in TREES:                    # 3 growth stages in flight; the portrait is the grown tree
        art = t['art'] if isinstance(t['art'], dict) else WOODLAND[t['id']]
        for st in range(3):
            render_tree(art, st, TREE_SMALL).save(A / f"tree-{t['id']}-{st}.png")
        render_tree(art, 2, TREE_PORTRAIT).save(A / 'ui' / f"portrait-tree-{t['id']}-0.png")
        print('drew tree', t['id'], render_tree(art, 2, TREE_SMALL).size)
    regions = {r: dict(v, ground='ground' if r == 'woodland' else f'ground-{r}', hills='hills' if r == 'woodland' else f'hills-{r}')
               for r, v in {**REGIONS, **TERRAIN_ONLY}.items()}
    rows = []
    for sp in SPECIES:
        has = sp['art'] is not None
        rows.append({'id': sp['id'], 'name': sp['name'], 'region': sp['region'], 'kind': sp['kind'],
                     'sprite': key(sp) if has else None, 'frames': 2 if has else 0,
                     'portrait': f'assets/ui/portrait-{key(sp)}' if has else None,
                     'pose': {'flyer': 'flying', 'wader': 'standing'}.get(sp['art']['template'], 'ground') if has else None,
                     'fact': sp['fact'], 'factChecked': sp['factChecked']})
    for t in TREES:
        rows.append({'id': t['id'], 'name': t['name'], 'region': t['region'], 'kind': 'tree',
                     'sprite': 'tree-' + t['id'], 'frames': 3, 'portrait': f"assets/ui/portrait-tree-{t['id']}", 'fact': t['fact'], 'factChecked': t['factChecked']})
    js = ('// GENERATED by tools/art/make_wildlife.py from tools/art/species.py: edit that, not this.\n'
          '// sprite: texture key prefix; frames are `${sprite}-0`..`${sprite}-${frames-1}` (trees: 3 growth stages). null = not drawn yet.\n'
          '// REGIONS[r].ground / .hills: terrain texture keys (make_regions.py; woodland = the original strips).\n'
          f'export const REGIONS = {json.dumps(regions, indent=2)};\n\n'
          'export const WILDLIFE = [\n' + ',\n'.join('  ' + json.dumps(r) for r in rows) + ',\n];\n')
    (ROOT / 'src' / 'wildlife.js').write_text(js)
    print('wrote src/wildlife.js:', len(rows), 'species,', sum(1 for r in rows if r['sprite']), 'with art')
    if preview and drawn:
        k = 6
        W = sum(f[0].width * 2 + 10 for _, f in drawn) + 10
        H = max(f[0].height for _, f in drawn) + 10
        c = Image.new('RGBA', (W, H), (90, 154, 60, 255))
        x = 6
        for sp, (a, b) in drawn:
            if sp['kind'] == 'bird':
                bg = Image.new('RGBA', (a.width * 2 + 4, H), (110, 198, 232, 255)); c.alpha_composite(bg, (x - 2, 0))
            c.alpha_composite(a, (x, H - 4 - a.height)); c.alpha_composite(b, (x + a.width + 2, H - 4 - b.height))
            x += a.width * 2 + 10
        c.resize((W * k, H * k), Image.NEAREST).save(preview)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else None)
