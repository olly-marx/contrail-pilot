"""Install the PixelLab city skylines (the user, 2026-10-24: every city, combined landmarks, big and recognisable).

    python3 tools/art/install_skylines.py

tools/art/pixellab/skylines/sky-<key>.png (pixflux 128x64, list in tools/art/pixellab/skylines.txt from
skyline_cities.tsv; redone ones in skylines-redo.txt) -> assets/landmark-<key>.png cropped to the drawing, base on
the bottom row; writes src/landmarks.js (city -> texture key, what it shows, size). GameScene draws them at
LANDMARK_SCALE, a little hazy, behind the city row. (Replaces make_landmarks.py, the 16 hand-drawn landmarks.)
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'tools/art/pixellab/skylines'


def main():
    out = {}
    for line in (ROOT / 'tools/art/pixellab/skyline_cities.tsv').read_text().splitlines():
        city, what = line.split('\t')
        key = city.lower().replace(' ', '')
        im = Image.open(SRC / f'sky-{key}.png').convert('RGBA')
        im = im.crop(im.getbbox())
        im.save(ROOT / 'assets' / f'landmark-{key}.png')
        out[city] = {'key': f'landmark-{key}', 'name': what, 'w': im.width, 'h': im.height}
    js = ('// GENERATED by tools/art/install_skylines.py: city -> PixelLab skyline texture (base on the bottom row).\n'
          f'export const LANDMARKS = {json.dumps(out, indent=2)};\n')
    (ROOT / 'src/landmarks.js').write_text(js)
    print(len(out), 'skylines')


if __name__ == '__main__':
    main()
