#!/usr/bin/env python3
"""Bake the collision masks into src/sim/masks.js (sim engine landing 2, 2026-10-25).

GameScene.alphaMask() reads a texture's alpha through a browser canvas: a pixel is solid when alpha > 40.
Node has no canvas, so the engine (and later the game too) uses these baked masks instead. Same rule, read
from the same PNGs. tests/sim-masks.cjs checks baked == canvas in the browser.
Run after changing any of these pictures: python3 tools/sim/bake-masks.py
"""
import base64, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
STORM_ART = ['c', 'd']   # = STORM_ART in src/GameScene.js
KEYS = ['plane', 'bird-0', 'bird-1'] + [f'storm-{p}-{v}' for v in STORM_ART for p in ('rise', 'hang')]

out = ['// GENERATED by tools/sim/bake-masks.py - do not edit. Collision masks: 1 bit per pixel (alpha > 40),',
       '// rows top to bottom, bits left to right, each row padded to whole bytes, base64.',
       'export const MASK_DATA = {']
for k in KEYS:
    im = Image.open(ROOT / 'assets' / f'{k}.png').convert('RGBA')
    w, h = im.size
    a = im.getchannel('A').load()
    stride = (w + 7) // 8
    buf = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            if a[x, y] > 40:
                buf[y * stride + x // 8] |= 0x80 >> (x % 8)
    out.append(f"  '{k}': {{ w: {w}, h: {h}, bits: '{base64.b64encode(bytes(buf)).decode()}' }},")
out.append('};')
(ROOT / 'src' / 'sim' / 'masks.js').write_text('\n'.join(out) + '\n')
print(f'baked {len(KEYS)} masks -> src/sim/masks.js')
